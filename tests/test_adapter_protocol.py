"""SR6-2: one adapter Protocol, and mypy enforces the declaration against it.

WHAT THESE TESTS PROVE
----------------------
Every book's declared class satisfies ``scrapers.protocol.BookAdapter``: no-arg
construction, an async ``scrape()``, and the three keywords ``run_scan`` passes
(``live``, ``scan_time``, ``sports_wanted``). ``SCRAPERS.adapter()`` is typed
``type[BookAdapter] | None``, so the scan's ``scrape()`` call is checked by mypy
instead of going through ``Any``. Two tests build throwaway modules and run mypy
with the project's own config: every declared class type-checks, and a
deliberately broken adapter (missing entry point, sync entry point, wrong return
type) is rejected.

WHAT THESE TESTS DO NOT PROVE
-----------------------------
They do not prove a feed works or that a book's markets are admissible; and the
Protocol says nothing about what a scrape may fetch, which the transport policy
(SR2-2) and the trust invariants own.
"""

from __future__ import annotations

import inspect
import os
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from typing import get_type_hints

from config.bookmakers import DECLARATIONS
from models.schemas import Match
from scrapers.protocol import AdapterClass
from scrapers.registry import SCRAPERS, ScraperRegistry

REPO_ROOT = Path(__file__).resolve().parents[1]
CONFIG_FILE = REPO_ROOT / "pyproject.toml"
MYPY_TIMEOUT_SECONDS = 300

#: The keyword arguments ``run_scan`` passes to every adapter.
SCRAPE_KEYWORDS = ("live", "scan_time", "sports_wanted")


def _run_mypy(files: list[Path]) -> subprocess.CompletedProcess[str]:
    """Type-check generated modules with the project's own mypy config.

    ``--follow-imports=silent`` keeps the check about the generated module: the
    packages themselves are covered by the repo-wide ``mypy .`` run in CI.
    """
    env = {**os.environ, "MYPYPATH": str(REPO_ROOT)}
    return subprocess.run(
        [
            sys.executable,
            "-m",
            "mypy",
            "--config-file",
            str(CONFIG_FILE),
            "--no-error-summary",
            "--follow-imports=silent",
            *(str(path) for path in files),
        ],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        timeout=MYPY_TIMEOUT_SECONDS,
        env=env,
    )


def _declared_classes_source() -> str:
    """A module that imports every declared adapter and types it as an adapter."""
    imports = "\n".join(
        f"from {spec.module} import {spec.class_name}" for spec in DECLARATIONS.values()
    )
    classes = ",\n    ".join(spec.class_name for spec in DECLARATIONS.values())
    return (
        '"""Generated by tests/test_adapter_protocol.py; type-checked only."""\n\n'
        "from scrapers.protocol import BookAdapter\n"
        f"{imports}\n\n"
        "declared: tuple[type[BookAdapter], ...] = (\n"
        f"    {classes},\n"
        ")\n"
    )


def test_every_declared_adapter_matches_the_protocol():
    assert set(DECLARATIONS) == set(SCRAPERS)

    for book in DECLARATIONS:
        adapter = SCRAPERS.adapter(book)
        assert adapter is not None, book
        assert adapter is SCRAPERS[book], book

        # No-argument construction, which is how the scan builds an adapter.
        required = [
            parameter
            for parameter in inspect.signature(adapter).parameters.values()
            if parameter.default is inspect.Parameter.empty
            and parameter.kind
            not in (inspect.Parameter.VAR_POSITIONAL, inspect.Parameter.VAR_KEYWORD)
        ]
        assert not required, (book, required)

        assert inspect.iscoroutinefunction(adapter.scrape), book
        parameters = inspect.signature(adapter.scrape).parameters
        for name in SCRAPE_KEYWORDS:
            assert name in parameters, (book, name)
            assert parameters[name].default is not inspect.Parameter.empty, (book, name)
        assert parameters["live"].default is False, book
        assert parameters["scan_time"].default is None, book
        assert parameters["sports_wanted"].default is None, book

        hints = get_type_hints(adapter.scrape)
        assert hints["live"] is bool, (book, hints["live"])
        assert hints["scan_time"] == datetime | None, (book, hints["scan_time"])
        assert hints["sports_wanted"] == tuple[str, ...] | list[str] | None, book
        assert hints["return"] == list[Match], (book, hints["return"])


def test_the_registry_types_a_resolved_class_as_a_book_adapter():
    assert get_type_hints(ScraperRegistry.__getitem__)["return"] == AdapterClass
    assert get_type_hints(ScraperRegistry.adapter)["return"] == AdapterClass | None

    # A declared book resolves; an unknown one is None, not a KeyError.
    assert SCRAPERS.adapter("mbet") is SCRAPERS["mbet"]
    assert SCRAPERS.adapter("not_a_book") is None


def test_mypy_accepts_every_declared_adapter(tmp_path: Path):
    module = tmp_path / "declared_adapters.py"
    module.write_text(_declared_classes_source(), encoding="utf-8")

    result = _run_mypy([module])

    assert result.returncode == 0, result.stdout + result.stderr


def test_mypy_rejects_broken_adapters(tmp_path: Path):
    broken = {
        "broken_missing_scrape.py": (
            '"""Mistake: the entry point is missing."""\n'
            "from scrapers.protocol import BookAdapter\n\n\n"
            "class NoScrape:\n    pass\n\n\n"
            "declared: type[BookAdapter] = NoScrape\n"
        ),
        "broken_sync_scrape.py": (
            '"""Mistake: the entry point is sync, not async."""\n'
            "from models.schemas import Match\n"
            "from scrapers.protocol import BookAdapter\n\n\n"
            "class SyncScrape:\n"
            "    def scrape(self) -> list[Match]:\n"
            "        return []\n\n\n"
            "declared: type[BookAdapter] = SyncScrape\n"
        ),
        "broken_wrong_return.py": (
            '"""Mistake: returns names, not matches."""\n'
            "from scrapers.protocol import BookAdapter\n\n\n"
            "class WrongReturn:\n"
            "    async def scrape(self, live: bool = False) -> list[str]:\n"
            "        return []\n\n\n"
            "declared: type[BookAdapter] = WrongReturn\n"
        ),
    }
    paths = []
    for name, source in broken.items():
        path = tmp_path / name
        path.write_text(source, encoding="utf-8")
        paths.append(path)

    result = _run_mypy(paths)
    output = result.stdout + result.stderr

    assert result.returncode != 0, "mypy accepted a broken adapter"
    for path in paths:
        assert path.name in output, output


def test_the_protocol_is_importable_without_loading_an_adapter():
    """The contract must not drag the ten scraper modules into an import."""
    modules = sorted(spec.module for spec in DECLARATIONS.values())
    code = (
        "import sys\n"
        "from scrapers.protocol import BookAdapter\n"
        f"books = {modules!r}\n"
        "loaded = sorted(name for name in books if name in sys.modules)\n"
        "raise SystemExit(1 if loaded else 0)\n"
    )

    result = subprocess.run(
        [sys.executable, "-c", code],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        timeout=120,
    )

    assert result.returncode == 0, result.stderr
