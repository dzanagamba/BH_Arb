#!/usr/bin/env python3
"""Regenerate the resolved dependency locks from the requirement manifests.

`requirements.txt` pins the eight direct runtime packages; `requirements.lock`
pins the whole runtime set those resolve to, transitives included. The Docker
image, CI installs and the SBOM all use the lock, so a build cannot silently pick
up a different `starlette` than the one that was tested.

`requirements-dev.lock` is the same idea for CI's tooling (pytest, ruff, mypy,
pip-audit, the SBOM generator). It is resolved in the same clean environment as
the runtime lock, after installing both manifests.

Regenerate after any manifest change and commit the two lock files together:

    python scripts/lock_requirements.py
    python scripts/lock_requirements.py --check

`--check` resolves into a temporary environment and fails when a committed lock
differs. It needs network access, so CI does not run it; the cheap consistency
test (`tests/test_dependency_lock.py`) runs on every push and catches the common
case where a direct pin was changed without regenerating.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
RUNTIME_MANIFEST = REPO_ROOT / "requirements.txt"
DEV_MANIFEST = REPO_ROOT / "requirements-dev.txt"
RUNTIME_LOCK = REPO_ROOT / "requirements.lock"
DEV_LOCK = REPO_ROOT / "requirements-dev.lock"

RUNTIME_HEADER = """\
# Generated by scripts/lock_requirements.py from requirements.txt.
# Do not edit by hand: change requirements.txt, then run
#   python scripts/lock_requirements.py
# and commit both files. This is the exact runtime set the Docker image and CI
# install, transitive dependencies included.
"""
DEV_HEADER = """\
# Generated by scripts/lock_requirements.py from requirements.txt and
# requirements-dev.txt. Do not edit by hand: change the manifests, then run
#   python scripts/lock_requirements.py
# and commit both files. This is the exact set CI installs, transitives included.
"""


def _install(venv: Path, manifests: list[Path]) -> list[str]:
    pip = venv / "bin" / "pip"
    args = [str(pip), "install", "--disable-pip-version-check", "-q"]
    for manifest in manifests:
        args.extend(["-r", str(manifest)])
    subprocess.run(args, check=True)
    frozen = subprocess.run(
        [
            str(pip),
            "freeze",
            "--exclude",
            "pip",
            "--exclude",
            "setuptools",
            "--exclude",
            "wheel",
        ],
        check=True,
        text=True,
        capture_output=True,
    ).stdout
    return sorted(line for line in frozen.splitlines() if line.strip())


def _resolve() -> tuple[str, str]:
    """Resolve both sets in one clean venv, sharing the runtime install."""
    with tempfile.TemporaryDirectory(prefix="bh-arb-lock-") as tmp:
        venv = Path(tmp) / "venv"
        subprocess.run([sys.executable, "-m", "venv", str(venv)], check=True)
        runtime = _install(venv, [RUNTIME_MANIFEST])
        development = _install(venv, [RUNTIME_MANIFEST, DEV_MANIFEST])
        # The second install only adds packages; keep the shared runtime pins
        # identical in both locks.
        runtime_pins = {line.split("==")[0].lower(): line for line in runtime}
        dev_pins = {line.split("==")[0].lower(): line for line in development}
        mismatched = {
            name: (pin, dev_pins.get(name))
            for name, pin in runtime_pins.items()
            if dev_pins.get(name) != pin
        }
        assert not mismatched, f"the dev resolution changed runtime pins: {mismatched}"
    return (
        RUNTIME_HEADER + "\n".join(runtime) + "\n",
        DEV_HEADER + "\n".join(development) + "\n",
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the committed locks differ from a fresh resolution",
    )
    args = parser.parse_args(argv)

    runtime_text, dev_text = _resolve()
    expected = {RUNTIME_LOCK: runtime_text, DEV_LOCK: dev_text}
    if args.check:
        problems: list[str] = []
        for path, text in expected.items():
            try:
                current = path.read_text(encoding="utf-8")
            except OSError as exc:
                problems.append(f"{path.name}: {exc}")
                continue
            if current != text:
                problems.append(f"{path.name} is out of date")
        if problems:
            for problem in problems:
                print(problem, file=sys.stderr)
            print("run: python scripts/lock_requirements.py", file=sys.stderr)
            return 1
        print("dependency locks are in sync")
        return 0

    for path, text in expected.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
